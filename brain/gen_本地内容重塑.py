def _content_hash(content):
    return hashlib.md5(content.encode()).hexdigest()[:12]


def _generate_content(src, rel, dst, dim):
    """从src/rel/dst组合生成唯一内容, 避免模板重复"""
    # 模板: 连接器1 [src] 连接器2 [rel] 连接器3 [dst] 连接器4 [dim延伸]
    connectors_a = ["系统运行中", "持续地", "在每次迭代中", "动态地", "递归地", "周期性", "自适应地", "实时地", "异步地", "协程中"]
    connectors_b = ["进而", "从而", "于是", "随后", "因此", "并将结果", "以此", "以此为引", "作为下一步", "继而"]
    connectors_c = ["最终", "最终驱动", "实现", "达成", "产出", "从而达成", "推动", "完成", "激活", "触发"]
    
    a = random.choice(connectors_a)
    b = random.choice(connectors_b)
    c = random.choice(connectors_c)
    
    # 生成2-3个变体组合
    variants = [
        f"{a}{src}{b}{rel}到{dst}，{c}{dim}维度的因果关联被强化",
        f"{src}通过持续的{rel}过程作用于{dst}，促进{dim}在当前循环中的自适应调整",
        f"当{src}与{dst}建立{rel}关系时，{dim}维度的稳态被重新校准以确保系统一致性",
        f"{src}的{rel}操作直接定向到{dst}，使{dim}在整个认知结构中保持动态平衡",
        f"{src}经过{rel}通道流向{dst}，在{dim}维度形成可追溯的因果印记",
        f"{src}周期性地{rel}给{dst}，维持{dim}维度的活性和响应能力",
        f"{src}与{dst}之间的{rel}反馈回路由{dim}维度的事件完整性约束",
    ]
    
    base = random.choice(variants)
    # 保证60-85字
    if len(base) < 60:
        filler = random.choice([
            "，这一过程发生在系统运行的每一阶段",
            "，进而构成{dim}维度的因果图谱基元",
            "，确保{dim}维度的语义一致性",
            "，这是{dim}维度自我维持的基础机制",
            "，体现了{dim}在认知架构中的因果角色",
        ]).format(dim=dim)
        base += filler
    elif len(base) > 90:
        base = base[:85]  # 截断
    
    return base


def _load_hippocampus():
    if HIP_FILE.exists():
        return json.loads(HIP_FILE.read_text())
    try:
        return json.loads((CLUSTER / "零·大脑" / "海马体·情景记忆.json").read_text())
    except:
        return {"causal_chains": []}


def _get_quality_report(hip):
    chains = hip.get("causal_chains", [])
    dim_stats = defaultdict(lambda: {"n": 0, "total_len": 0, "uniq": set()})
    for c in chains:
        d = c.get("dimension", "未分类")
        content = c.get("content", "") or ""
        dim_stats[d]["n"] += 1
        dim_stats[d]["total_len"] += len(content)
        dim_stats[d]["uniq"].add(content)
    report = []
    for d, s in sorted(dim_stats.items(), key=lambda x: x[1]["total_len"]/x[1]["n"] if x[1]["n"] else 0):
        avg = s["total_len"] / s["n"] if s["n"] else 0
        dedup_pct = len(s["uniq"]) / s["n"] * 100 if s["n"] else 100
        report.append({"dim": d, "avg": avg, "count": s["n"], "dedup_pct": dedup_pct})
    return report


def enrich(target_dims=None, max_replace_ratio=0.2):
    """替换最短链的内容为唯一生成内容"""
    t0 = time.time()
    hip = _load_hippocampus()
    chains = hip.get("causal_chains", [])
    if not chains:
        return {"status": "error", "reason": "no chains"}

    dim_map = defaultdict(list)
    all_content_hashes = set()
    for idx, c in enumerate(chains):
        d = c.get("dimension", "未分类")
        dim_map[d].append((idx, c))
        content = c.get("content", "") or ""
        all_content_hashes.add(_content_hash(content))

    if target_dims is None:
        report = _get_quality_report(hip)
        target_dims = [r["dim"] for r in report if r["avg"] < 35 and r["count"] > 10 and r["dim"] in DOMAIN_CONCEPTS]

    total_replaced = 0
    dim_results = []

    for dim in target_dims:
        if dim not in DOMAIN_CONCEPTS:
            continue
        dim_chains = dim_map.get(dim, [])
        if len(dim_chains) == 0:
            continue

        # 按内容长度排序（最短在前）
        dim_chains.sort(key=lambda x: len(x[1].get("content", "") or ""))

        # 选最短的 max_replace_ratio 比例进行替换
        replace_count = max(1, int(len(dim_chains) * max_replace_ratio))
        to_replace = dim_chains[:replace_count]

        concepts = DOMAIN_CONCEPTS[dim]
        replaced = 0
        for idx, chain in to_replace:
            # 从领域概念中选择组合
            src = random.choice(concepts["sources"])
            rel = random.choice(concepts["rels"])
            dst = random.choice(concepts["targets"])
            
            # 生成唯一内容 (尝试最多5次避免全局重复)
            for retry in range(10):
                content = _generate_content(src, rel, dst, dim)
                h = _content_hash(content)
                if h not in all_content_hashes:
                    all_content_hashes.add(h)
                    break
                # 如果重复，换一组概念再试
                src = random.choice(concepts["sources"])
                rel = random.choice(concepts["rels"])
                dst = random.choice(concepts["targets"])

            chain["src"] = src
            chain["rel"] = rel
            chain["dst"] = dst
            chain["content"] = content
            chains[idx] = chain
            replaced += 1

        total_replaced += replaced
        after_avg = sum(len(c.get("content","") or "") for _, c in dim_chains) / len(dim_chains)
        after_uniq = len(set(_content_hash(c.get("content","") or "") for _, c in dim_chains))
        dedup_pct = after_uniq / len(dim_chains) * 100
        dim_results.append({"dim": dim, "replaced": replaced, "total": len(dim_chains),
                            "after_avg": f"{after_avg:.0f}chars",
                            "dedup_pct": f"{dedup_pct:.0f}%"})

    # 写回海马体（带备份）
    if total_replaced > 0:
        BACKUP.parent.mkdir(parents=True, exist_ok=True)
        _btmp = str(BACKUP) + ".tmp." + str(os.getpid())
        with open(_btmp, "w", encoding="utf-8") as _f:
            json.dump(hip, _f, ensure_ascii=False, indent=2)
        os.rename(_btmp, str(BACKUP))

        hip["causal_chains"] = chains
        hip["last_modified"] = time.time()
        hip["content_enrich_source"] = "gen_本地内容重塑"

        HIP_FILE.parent.mkdir(parents=True, exist_ok=True)
        _hippocampus_write_safe(hip)

    elapsed = time.time() - t0
    return {
        "status": "ok",
        "total_replaced": total_replaced,
        "dims": dim_results,
        "elapsed": f"{elapsed:.1f}s"
    }


def pulse(cycle_num):
    if cycle_num % 5 != 0:
        return {"status": "skipped", "reason": "not my cycle"}

    report = _get_quality_report(_load_hippocampus())
    bad_dims = [r["dim"] for r in report if r["avg"] < 30 and r["dim"] in DOMAIN_CONCEPTS]
    if not bad_dims:
        return {"status": "skipped", "reason": "no bad dims"}

    result = enrich(target_dims=bad_dims[:3], max_replace_ratio=0.15)
    return result


def auto_pulse():
    try:
        if BRAIN_STATE.exists():
            state = json.loads(BRAIN_STATE.read_text())
            cycle = state.get("cycle", 0)
        else:
            cycle = 0
        return pulse(cycle)
    except Exception as e:
        print(f"[内容重塑] auto_pulse error: {e}")
        return {"status": "error", "reason": str(e)}


